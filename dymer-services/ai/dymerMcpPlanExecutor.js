const ollamaMcpDeterministic = require('./ollamaMcpDeterministic');
const dymerMultiCatalogOrchestrator = require('./dymerMultiCatalogOrchestrator');

function publishedIndexes(models) {
    const values = [];
    for (const model of Array.isArray(models) ? models : []) {
        if (model?.index) values.push(model.index);
        for (const instance of Array.isArray(model?.instances) ? model.instances : []) {
            if (instance?.index) values.push(instance.index);
        }
    }
    return [...new Set(values.map(value => String(value).trim()).filter(Boolean))];
}

function normalizeCatalogToken(value) {
    return String(value || '')
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .toLocaleLowerCase()
        .replace(/[^a-z0-9]+/g, ' ')
        .trim();
}

function resolveCatalogIndexes(catalogName, models) {
    const wanted = normalizeCatalogToken(catalogName);
    if (!wanted) return [];
    const values = [];
    const visit = (item, inheritedMatch = false) => {
        if (!item || typeof item !== 'object') return;
        const aliases = [
            item.index, item.name, item.title, item.label, item.alias,
            item.modelName, item.catalogName, item.value
        ].map(normalizeCatalogToken).filter(Boolean);
        const matched = inheritedMatch || aliases.some(alias =>
            alias === wanted || alias.split(' ').includes(wanted) || wanted.split(' ').includes(alias)
        );
        if (matched && item.index) values.push(String(item.index).trim());
        for (const child of Array.isArray(item.instances) ? item.instances : []) visit(child, matched);
    };
    for (const model of Array.isArray(models) ? models : []) visit(model, false);
    return [...new Set(values.filter(Boolean))];
}

function validateArguments(tool, args) {
    const schema = tool?.inputSchema || {};
    const properties = schema.properties || {};
    const required = Array.isArray(schema.required) ? schema.required : [];
    const clean = {};

    for (const [key, value] of Object.entries(args || {})) {
        if (!Object.prototype.hasOwnProperty.call(properties, key)) continue;

        const isRequired = required.includes(key);
        const isEmptyString = typeof value === 'string' && value.trim() === '';
        const isEmptyArray = Array.isArray(value) && value.length === 0;
        const isNullish = value === undefined || value === null;

        // Optional empty values generated by the LLM must be omitted.
        // Schemas such as z.string().min(1).optional() reject an empty string.
        if (!isRequired && (isNullish || isEmptyString || isEmptyArray)) continue;

        clean[key] = typeof value === 'string' ? value.trim() : value;
    }

    const missing = required.filter(key =>
        clean[key] === undefined ||
        clean[key] === null ||
        (typeof clean[key] === 'string' && clean[key].trim() === '') ||
        (Array.isArray(clean[key]) && clean[key].length === 0)
    );

    if (missing.length) {
        const error = new Error(`Argomenti obbligatori mancanti per ${tool.name}: ${missing.join(', ')}`);
        error.statusCode = 422;
        throw error;
    }

    return clean;
}

async function executePlan({ plan, tools, agent, prompt, dymeruser, publishedModels }) {
    if (!plan) return { executed: false, reason: 'missing_plan' };
    if (plan.kind === 'general_chat') return { executed: false, reason: 'general_chat' };
    if (plan.kind === 'workflow') {
        if (plan.workflow !== 'multi_catalog_entity_search') return { executed: false, reason: 'unknown_workflow' };
        const workflowPlan = dymerMultiCatalogOrchestrator.parseMultiCatalogPrompt(prompt, publishedModels);
        if (!workflowPlan.matched) return { executed: false, reason: workflowPlan.reason || 'workflow_not_matched' };
        const result = await dymerMultiCatalogOrchestrator.runMultiCatalogOrchestration({
            agentId: agent._id, prompt, publishedModels, dymeruser
        });
        return { executed: true, kind: 'workflow', answer: result.answer, workflow: plan.workflow, result };
    }
    const tool = (Array.isArray(tools) ? tools : []).find(item => item.name === plan.tool);
    if (!tool) return { executed: false, reason: 'tool_not_published' };
    let args = { ...(plan.arguments || {}) };
    if (plan.tool === 'search_entities') {
        const catalogName = args.catalog_name || args.catalogName || args.catalog || null;
        delete args.catalog_name;
        delete args.catalogName;
        delete args.catalog;

        const explicitIndexes = [
            ...(Array.isArray(args.indexes) ? args.indexes : []),
            ...(args.index ? [args.index] : [])
        ].map(value => String(value).trim()).filter(Boolean);

        let resolvedIndexes = explicitIndexes;
        if (!resolvedIndexes.length && catalogName) {
            resolvedIndexes = resolveCatalogIndexes(catalogName, publishedModels);
        }
        if (!resolvedIndexes.length || plan.scope?.type === 'all_published_indexes') {
            resolvedIndexes = publishedIndexes(publishedModels);
        }
        if (!resolvedIndexes.length) {
            return { executed: false, reason: 'published_indexes_not_available' };
        }

        args.indexes = [...new Set(resolvedIndexes)];
        delete args.index;
        if (args.query === undefined) args.query = '';
        if (args.page === undefined) args.page = 1;
        if (args.limit === undefined) args.limit = 20;

        console.log('[MCP PLAN EXECUTOR] search_entities scope resolved', {
            catalogName,
            scopeType: plan.scope?.type || null,
            indexes: args.indexes,
            query: args.query,
            page: args.page,
            limit: args.limit
        });
    }
    args = validateArguments(tool, args);
    const result = await ollamaMcpDeterministic.runDeterministicToolPrompt({
        agentId: agent._id, serverId: 'dymer', tool: plan.tool, arguments: args,
        prompt, responseLimit: args.limit, responseGoal: plan.responseGoal, dymeruser
    });
    return { executed: true, kind: 'tool_call', answer: result.answer, result };
}

module.exports = { executePlan, publishedIndexes, resolveCatalogIndexes, validateArguments };
